-- Public directory intentionally returns only name, qualification and graduation year.
create or replace function public.search_public_alumni(p_query text default null, p_qualification text default null)
returns table (full_name text, qualification_name text, graduation_year integer)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select p.full_name, q.qualification_name, q.graduation_year
  from public.alumni_profiles p
  join public.alumni_qualifications q on q.alumni_id = p.id
  where p.visibility_status = 'public'
    and (nullif(trim(p_query),'') is null or p.full_name ilike '%' || trim(p_query) || '%')
    and (nullif(trim(p_qualification),'') is null or q.qualification_name ilike '%' || trim(p_qualification) || '%')
  order by p.full_name, q.graduation_year desc nulls last
  limit 100;
$$;

-- Public ticker may show announcement headline/teaser only, never applicant or company contact data.
create or replace function public.get_public_job_ticker()
returns table (announcement_number bigint, company_display_name text, title text, teaser text, published_at timestamptz)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select j.announcement_number, j.company_display_name, j.title, j.teaser, j.published_at
  from public.job_announcements j
  where j.status = 'approved'
    and (j.expires_at is null or j.expires_at >= now())
  order by j.is_featured desc, j.published_at desc nulls last, j.announcement_number desc
  limit 30;
$$;

create or replace function public.get_public_training_ticker()
returns table (announcement_number bigint, title text, teaser text, published_at timestamptz)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select t.announcement_number, t.title, t.teaser, t.published_at
  from public.training_announcements t
  where t.status = 'published'
    and (t.expires_at is null or t.expires_at >= now())
  order by t.published_at desc nulls last, t.announcement_number desc
  limit 20;
$$;

